/** Render the actual React DotPattern into the approved glass setup HTML. */
import { readFileSync, writeFileSync } from "node:fs";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { DotPattern } from "../components/ui/dot-pattern";

const source = new URL("../design/glass-setup/template.html", import.meta.url);
const destination = new URL("../design/glass-setup/preview.html", import.meta.url);
const dots = renderToStaticMarkup(
  createElement(DotPattern, { width: 24, height: 24, cx: 1, cy: 1, cr: 1, className: "setup-dot-pattern" }),
);
const style = `
/* Full-canvas background; the glass panel sits above and blurs the dots. */
.native{position:relative;isolation:isolate;background-image:none;background-color:#101114}
.native>.setup-dot-pattern{position:absolute;inset:0;width:100%;height:100%;pointer-events:none;z-index:0;fill:rgb(255 255 255 / 22%);mask-image:none;-webkit-mask-image:none}
.native>header,.native>main,.native>footer{position:relative;z-index:1}
@supports ((backdrop-filter:blur(1px)) or (-webkit-backdrop-filter:blur(1px))){
  .native .dialog{background:rgb(18 18 20 / 18%);-webkit-backdrop-filter:blur(0.5px) saturate(100%);backdrop-filter:blur(0.5px) saturate(100%)}
}
.native .dialog form>div:has(>[data-slot=input]),.native .dialog form>span{background:rgb(16 17 20 / 78%)}
@media(prefers-reduced-transparency:reduce){.native .dialog{background:#19191b;-webkit-backdrop-filter:none;backdrop-filter:none}.native>.setup-dot-pattern{fill:rgb(255 255 255 / 12%)}}
`;
const html = readFileSync(source, "utf8")
  .replace('<section class="mock dark native">', `<section class="mock dark native">${dots}`)
  .replace("</style>", `${style}</style>`);
if (process.argv.includes("--production")) {
  const production = html
    .replace(/<title>[^<]*<\/title>/, "<title>T3 Code · Umbrel setup</title>")
    .replace(/<script>[\s\S]*?<\/script>/g, "")
    .replace("</style>", "html,body{background:#101114;color:#f5f5f5}.native{min-height:100svh;display:flex;flex-direction:column}.native>main{flex:1}</style>")
    .replace("<form>", '<form method="post" action="/umbrel/pair">')
    .replace(/<p hidden="" class="feedback"[\s\S]*?<\/p>/g, "")
    .replace('<button type="button" class="text-button">Already paired? Open T3 Code</button>',
      '<a class="text-button" href="/">Already paired? Open T3 Code</a>')
    .replace(/<button([^>]*)>Set up<\/button>/g, (_match, attributes: string) =>
      `<a${attributes.replace(/ type="button"/g, "")} href="/umbrel/connect">Set up</a>`);
  writeFileSync(new URL("../container/welcome.mjs", import.meta.url),
    "// Generated by npm run build:setup. Edit design/glass-setup/template.html or the renderer.\n" +
    "export const welcomePage = " + JSON.stringify(production) + ";\n");
} else {
  writeFileSync(destination, html);
}
console.log(process.argv.includes("--production") ? "Generated container/welcome.mjs" : `Rendered ${destination.pathname}`);
